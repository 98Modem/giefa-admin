-- Records the external health checks that query both GIEFA and Game Predictor.

begin;

create table if not exists public.system_health_check_runs (
  id bigint generated by default as identity primary key,
  checked_at timestamptz not null default now(),
  source text not null default 'unknown',
  all_healthy boolean not null,
  results jsonb not null,
  created_at timestamptz not null default now(),
  constraint system_health_check_runs_source_length check (char_length(source) between 1 and 60),
  constraint system_health_check_runs_results_array check (jsonb_typeof(results) = 'array')
);

create index if not exists system_health_check_runs_checked_at_idx
  on public.system_health_check_runs (checked_at desc);

alter table public.system_health_check_runs enable row level security;

revoke all on table public.system_health_check_runs from anon, authenticated;
grant select, insert on table public.system_health_check_runs to service_role;
grant usage, select on sequence public.system_health_check_runs_id_seq to service_role;

commit;
